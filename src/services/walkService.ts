import * as Sentry from '@sentry/node';
import { emergencyPlan } from '../ai/emergencyPlan';
import { failureStage, PlannerError, type PlannerFailureReason } from '../ai/errors';
import { validateDomainPlan } from '../ai/validationPipeline';
import { notRunReport, summarize, type ValidationReport, type ValidationSummary } from '../ai/validationReport';
import type { WalkPlan, WalkPlanner } from '../ai/walkPlanner';
import { contextErrorCategory, modelErrorCategory } from '../observability/errorCategory';
import { annotateActiveSpan, captureUnexpected, withAgentSpan, withStepSpan, withToolSpan } from '../observability/tracing';
import { defaultSafetyEngine, type SafetyEngine } from '../safety/engine';
import { ContextBuilder, summarizeContext, type WalkRequest } from '../context/contextBuilder';
import type { ContextSummary, OutdoorContext } from '../context/types';
import { DEFAULT_BUDGETS, type Budgets, type RequestScope } from './requestScope';

/** Fixed, human-readable wording for the fallback case. Never contains provider text, rule ids or plan text. */
export const FALLBACK_MESSAGES = {
  not_configured: 'No AI model is configured, so a deterministic walk was used.',
  model_unavailable: 'The AI planner was unavailable, so a deterministic walk was used.',
  rejected: 'PocketWalk could not safely generate a plan, so a safe fallback was used.',
} as const;

export function fallbackMessage(reason: PlannerFailureReason): string {
  switch (failureStage(reason)) {
    case 'none':
      return FALLBACK_MESSAGES.not_configured;
    case 'model':
      return reason === 'unknown' ? FALLBACK_MESSAGES.rejected : FALLBACK_MESSAGES.model_unavailable;
    default:
      return FALLBACK_MESSAGES.rejected;
  }
}

export interface WalkMeta {
  /** `model`: generated by Gemma and validated. `fallback`: deterministic text, not AI. */
  planner: WalkPlanner['kind'];
  provider?: string;
  model?: string;
  /** Present only when `planner` is `fallback`. A closed set of reasons, never raw error text. */
  fallbackReason?: PlannerFailureReason;
  /**
   * Present only on fallback. `deterministic`: the Checkpoint 2 fallback planner (passed validation).
   * `emergency`: the fixed by-the-door plan, used only if the deterministic fallback itself failed validation.
   */
  fallbackSource?: 'deterministic' | 'emergency';
  /** Present only on fallback. One fixed sentence per outcome class. */
  message?: string;
  /**
   * What happened to the model's output, stage by stage. `not_run` means the stage never saw it
   * (e.g. the model timed out, or no model is configured). `repaired: true` means the model's plan was
   * normalised (whitespace, invisible characters, markdown) before it was shown.
   */
  validation: ValidationSummary;
  /** Real elapsed wall-clock time for the whole run. */
  durationMs: number;
  /** Real measured time of the model call (only when the model answered). */
  modelLatencyMs?: number;
  /** Real measured time of the whole validation pipeline (parse, schema, repair, business, safety). Model path only. */
  validationLatencyMs?: number;
  /** Real measured time of the safety rules alone. Present only when the safety stage ran. */
  safetyLatencyMs?: number;
  /** Real measured time of the fallback planner plus validating its output. Present only on fallback. */
  fallbackLatencyMs?: number;
  /** Real measured time to build the outdoor context (weather + daylight). */
  contextLatencyMs: number;
  /** Real measured time of the weather lookup. Present only when a lookup was attempted, even if it failed. */
  weatherLatencyMs?: number;
  /** What PocketWalk knew about the outdoors for this walk. Enumerated facts only, never a location. */
  context: ContextSummary;
}

export interface WalkResult {
  plan: WalkPlan;
  meta: WalkMeta;
}

export class WalkService {
  /**
   * @param primary  the model planner, or null when no model is configured
   * @param fallback deterministic planner used when the model path cannot deliver a valid plan
   */
  constructor(
    private readonly primary: WalkPlanner | null,
    private readonly fallback: WalkPlanner,
    private readonly contextBuilder: ContextBuilder = new ContextBuilder(),
    private readonly safety: SafetyEngine = defaultSafetyEngine,
    private readonly budgets: Budgets = DEFAULT_BUDGETS,
  ) {}

  /** One PocketWalk run, traced as a single agent invocation with child steps. */
  async planWalk(request: WalkRequest, scope?: RequestScope): Promise<WalkResult> {
    const started = performance.now();
    return withAgentSpan(async () => {
      // Request shape only: two enumerated values. No location, no free text.
      annotateActiveSpan({ 'pocketwalk.walk_duration_minutes': request.minutes, 'pocketwalk.energy': request.energy });
      const { context, timings: contextTimings } = await withToolSpan('context.build', () =>
        this.contextBuilder.build(
          request,
          scope
            ? {
                signal: scope.signal,
                // Weather may not eat the time the model needs, nor the reserve for validation and the response.
                weatherTimeoutMs: Math.max(0, scope.remainingMs() - this.budgets.responseReserveMs - this.budgets.minModelBudgetMs),
              }
            : undefined,
        ),
      );
      scope?.throwIfAbandoned(); // the client left during context: start nothing new
      const summary = summarizeContext(context);
      annotateActiveSpan({
        'pocketwalk.weather': summary.weather,
        'pocketwalk.daylight': summary.daylight,
        'pocketwalk.context_ms': contextTimings.contextMs,
        ...(summary.weatherFailure ? { 'pocketwalk.weather_failure': summary.weatherFailure } : {}),
        ...(summary.weatherFailure && contextErrorCategory(summary.weatherFailure)
          ? { 'pocketwalk.context.error_category': contextErrorCategory(summary.weatherFailure) as string }
          : {}),
        'pocketwalk.context.degraded': summary.weather === 'unavailable',
      });
      const contextMeta = {
        contextLatencyMs: contextTimings.contextMs,
        ...(contextTimings.weatherMs !== undefined ? { weatherLatencyMs: contextTimings.weatherMs } : {}),
        context: summary,
      };

      let reason: PlannerFailureReason = 'not_configured';
      let report: ValidationReport = notRunReport();
      const modelBudgetMs = scope ? scope.remainingMs() - this.budgets.responseReserveMs : undefined;
      if (this.primary && modelBudgetMs !== undefined && modelBudgetMs < this.budgets.minModelBudgetMs) {
        // Not enough request time left for the model to answer: serve the safe fallback now instead of waiting in vain.
        reason = 'timeout';
        annotateActiveSpan({ 'pocketwalk.deadline_skipped_model': true });
      } else if (this.primary) {
        try {
          const { plan, timings, validation } = await this.primary.plan(
            context,
            scope ? { signal: scope.signal, timeoutMs: modelBudgetMs as number } : undefined,
          );
          annotateActiveSpan({
            'pocketwalk.fallback': false,
            'pocketwalk.duration_ms': Math.round(performance.now() - started),
            ...(timings?.modelMs !== undefined ? { 'pocketwalk.model_ms': timings.modelMs } : {}),
            ...(validation ? validationAttributes(validation) : {}),
          });
          return {
            plan,
            meta: {
              planner: this.primary.kind,
              provider: this.primary.provider,
              model: this.primary.model,
              modelLatencyMs: timings?.modelMs,
              ...(validation
                ? {
                    validationLatencyMs: validation.timingsMs.totalMs,
                    ...(validation.timingsMs.safetyMs !== undefined ? { safetyLatencyMs: validation.timingsMs.safetyMs } : {}),
                  }
                : {}),
              durationMs: Math.round(performance.now() - started),
              validation: summarize(validation ?? { ...notRunReport(), parse: 'passed', schema: 'passed', business: 'passed', safety: 'passed' }),
              ...contextMeta,
            },
          };
        } catch (err) {
          if (err instanceof PlannerError) {
            reason = err.reason;
            if (err.report) report = err.report;
          } else {
            // A bug, not an expected model failure. Still serve a safe walk, but make it visible.
            reason = 'unknown';
            captureUnexpected(err, 'planner');
          }
        }
      }

      scope?.throwIfAbandoned();
      return this.serveFallback(context, reason, report, started, contextMeta);
    });
  }

  /** The labelled, validated fallback. If even this fails validation (a bug), the fixed emergency plan is served. */
  private async serveFallback(
    context: OutdoorContext,
    reason: PlannerFailureReason,
    report: ValidationReport,
    started: number,
    contextMeta: Pick<WalkMeta, 'contextLatencyMs' | 'weatherLatencyMs' | 'context'>,
  ): Promise<WalkResult> {
    annotateActiveSpan({
      'pocketwalk.fallback': true,
      'pocketwalk.fallback_reason': reason,
      'pocketwalk.failure_stage': failureStage(reason),
      'pocketwalk.error_category': modelErrorCategory(reason),
      ...(report.failureCodes.length > 0 ? { 'pocketwalk.failure_codes': report.failureCodes.join(',') } : {}),
      ...validationAttributes(report),
    });

    // The fallback is deterministic, but it is held to the SAME business and safety rules as model
    // output. If it ever fails them (a bug), the fixed emergency plan is served instead, and labelled.
    const fallbackStart = performance.now();
    const { plan: fallbackPlan } = await withStepSpan('pocketwalk.fallback', 'fallback plan', () =>
      this.fallback.plan(context),
    );
    const check = await validateDomainPlan(fallbackPlan, context, this.safety);
    let plan = fallbackPlan;
    let fallbackSource: 'deterministic' | 'emergency' = 'deterministic';
    if (!check.ok) {
      plan = emergencyPlan(context.minutes);
      fallbackSource = 'emergency';
      // A deterministic fallback failing its own rules is a bug worth knowing about. Codes only, no plan text.
      Sentry.captureMessage('PocketWalk fallback plan failed validation; emergency plan served', {
        level: 'error',
        extra: { stage: check.stage, codes: check.codes },
      });
    }
    annotateActiveSpan({
      'pocketwalk.fallback_source': fallbackSource,
      'pocketwalk.duration_ms': Math.round(performance.now() - started),
      'pocketwalk.fallback_ms': Math.round((performance.now() - fallbackStart) * 100) / 100,
    });

    return {
      plan,
      meta: {
        planner: this.fallback.kind,
        fallbackReason: reason,
        fallbackSource,
        message: fallbackMessage(reason),
        validation: summarize(report),
        ...(report.timingsMs.totalMs > 0 ? { validationLatencyMs: report.timingsMs.totalMs } : {}),
        ...(report.timingsMs.safetyMs !== undefined ? { safetyLatencyMs: report.timingsMs.safetyMs } : {}),
        fallbackLatencyMs: Math.round((performance.now() - fallbackStart) * 100) / 100,
        durationMs: Math.round(performance.now() - started),
        ...contextMeta,
      },
    };
  }

  /**
   * The request deadline passed before the normal path finished. Build the safe, validated fallback from what is known
   * (no weather: there is no time left to ask) so the person still gets an honest walk. Never calls a provider.
   */
  async planFallbackNow(request: WalkRequest): Promise<WalkResult> {
    const started = performance.now();
    return withAgentSpan(async () => {
      annotateActiveSpan({
        'pocketwalk.walk_duration_minutes': request.minutes,
        'pocketwalk.energy': request.energy,
        'pocketwalk.deadline_exceeded': true,
        'pocketwalk.fallback': true,
        'pocketwalk.fallback_reason': 'timeout',
        'pocketwalk.failure_stage': failureStage('timeout'),
        'pocketwalk.error_category': modelErrorCategory('timeout'),
      });
      const context: OutdoorContext = request.location
        ? { minutes: request.minutes, energy: request.energy, availability: { weather: 'unavailable', daylight: 'unavailable' }, weatherFailure: 'timeout', guidance: [] }
        : { minutes: request.minutes, energy: request.energy, availability: { weather: 'not_requested', daylight: 'not_requested' }, guidance: [] };
      return this.serveFallback(context, 'timeout', notRunReport(), started, {
        contextLatencyMs: 0,
        context: summarizeContext(context),
      });
    });
  }
}

/** Span attributes for a validation report: stage results and repair codes only. */
function validationAttributes(r: ValidationReport): Record<string, string | number | boolean> {
  return {
    'pocketwalk.validation.parse': r.parse,
    'pocketwalk.validation.schema': r.schema,
    'pocketwalk.validation.business': r.business,
    'pocketwalk.validation.safety': r.safety,
    'pocketwalk.plan_repaired': r.repaired,
    ...(r.repairs.length > 0 ? { 'pocketwalk.repair_codes': r.repairs.join(',') } : {}),
    'pocketwalk.validation_ms': r.timingsMs.totalMs,
  };
}
